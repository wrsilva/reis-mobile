import { resolve } from 'node:path';

import { createProbe } from './project-probe.mjs';

const FLUTTER_PLATFORMS = ['android', 'ios', 'web', 'macos', 'linux', 'windows'];
const GRADLE_ROOT_FILES = ['settings.gradle.kts', 'settings.gradle', 'build.gradle.kts', 'build.gradle'];

/**
 * Detection rules in priority order. Cross-platform stacks come first because their
 * projects also contain native Android/iOS folders.
 */
const RULES = [
  { id: 'flutter', detect: detectFlutter },
  { id: 'react-native', detect: detectReactNative },
  { id: 'kotlin-multiplatform', detect: detectKotlinMultiplatform },
  { id: 'android', detect: detectAndroid },
  { id: 'ios', detect: detectIos },
];

export const DETECTABLE_STACKS = RULES.map((rule) => rule.id);

/**
 * @returns {Promise<{ projectDir: string, stack: string, language: string|null,
 *   languages: string[], platforms: string[], variant: string|null, evidence: string[],
 *   candidates: object[] }>}
 */
export async function detectStack(projectDir = process.cwd()) {
  const root = resolve(projectDir);
  const probe = createProbe(root);
  const candidates = [];

  for (const rule of RULES) {
    const result = await rule.detect(probe);
    if (result) candidates.push({ stack: rule.id, variant: null, ...result });
  }

  const primary = candidates[0];
  if (!primary) {
    return {
      projectDir: root,
      stack: 'unknown',
      language: null,
      languages: [],
      platforms: [],
      variant: null,
      evidence: [],
      candidates,
    };
  }

  return {
    projectDir: root,
    stack: primary.stack,
    language: primary.languages[0] ?? null,
    languages: primary.languages,
    platforms: primary.platforms,
    variant: primary.variant,
    evidence: primary.evidence,
    candidates,
  };
}

async function detectFlutter(probe) {
  const pubspec = await probe.read('pubspec.yaml');
  if (!pubspec) return null;
  // A pure Dart package has a pubspec too; only the Flutter SDK dependency makes it mobile.
  if (!/^\s*sdk:\s*flutter\s*$/m.test(pubspec) && !/^flutter:\s*$/m.test(pubspec)) return null;

  const platforms = [];
  for (const platform of FLUTTER_PLATFORMS) {
    if (await probe.isDir(platform)) platforms.push(platform);
  }
  const native = unique([...(await probe.languages('android')), ...(await probe.languages('ios'))]);
  const variant = /^\s*plugin:\s*$/m.test(pubspec) ? 'plugin' : null;

  return {
    languages: unique(['dart', ...native]),
    platforms,
    variant,
    evidence: ['pubspec.yaml declares the Flutter SDK', ...platforms.map((p) => `${p}/ directory`)],
  };
}

async function detectReactNative(probe) {
  const manifest = parseJson(await probe.read('package.json'));
  if (!manifest) return null;
  const dependencies = { ...manifest.dependencies, ...manifest.devDependencies, ...manifest.peerDependencies };
  if (!dependencies['react-native']) return null;

  const isExpo = Boolean(dependencies.expo);
  const platforms = [];
  for (const platform of ['android', 'ios']) {
    if (await probe.isDir(platform)) platforms.push(platform);
  }
  const evidence = [`package.json depends on react-native ${dependencies['react-native']}`];
  if (isExpo && platforms.length === 0) {
    platforms.push('android', 'ios');
    evidence.push('Expo managed workflow (native folders are generated by prebuild)');
  }

  const script = (await probe.exists('tsconfig.json')) ? 'typescript' : 'javascript';
  const native = unique([...(await probe.languages('android')), ...(await probe.languages('ios'))]);

  return {
    languages: unique([script, ...native]),
    platforms,
    variant: isExpo ? 'expo' : null,
    evidence,
  };
}

async function detectKotlinMultiplatform(probe) {
  const scripts = await probe.findFiles((name) => name === 'build.gradle.kts', { maxDepth: 1, limit: 20 });
  let multiplatformScript = null;
  const targets = new Set();

  for (const path of scripts) {
    const content = (await probe.read(path)) ?? '';
    if (/kotlin\("multiplatform"\)|org\.jetbrains\.kotlin\.multiplatform|kotlinMultiplatform/.test(content)) {
      multiplatformScript ??= path;
    }
    if (/androidTarget\s*\(|\bandroid\s*\(\s*\)/.test(content)) targets.add('android');
    if (/ios(X64|Arm64|SimulatorArm64)\s*\(/.test(content)) targets.add('ios');
    if (/\bjvm\s*\(/.test(content)) targets.add('desktop');
    if (/\b(js|wasmJs)\s*\(/.test(content)) targets.add('web');
  }
  if (!multiplatformScript) return null;

  return {
    languages: unique(['kotlin', ...(await probe.languages('iosApp'))]),
    platforms: [...targets],
    evidence: [`${multiplatformScript} applies the Kotlin Multiplatform plugin`],
  };
}

async function detectAndroid(probe) {
  const gradleFile = await firstExisting(probe, GRADLE_ROOT_FILES);
  if (!gradleFile) return null;

  const manifests = await probe.findFiles((name) => name === 'AndroidManifest.xml', { maxDepth: 4, limit: 1 });
  const gradleScripts = await probe.findFiles((name) => /^build\.gradle(\.kts)?$/.test(name), {
    maxDepth: 2,
    limit: 20,
  });
  let androidPluginScript = null;
  for (const path of gradleScripts) {
    if (/com\.android\.(application|library)|android\.application|android\.library/.test((await probe.read(path)) ?? '')) {
      androidPluginScript = path;
      break;
    }
  }
  if (!manifests.length && !androidPluginScript) return null;

  const languages = (await probe.languages('.')).filter((language) => language === 'kotlin' || language === 'java');
  return {
    languages: languages.length ? languages : ['kotlin'],
    platforms: ['android'],
    evidence: [
      `${gradleFile} at project root`,
      ...(androidPluginScript ? [`${androidPluginScript} applies the Android Gradle plugin`] : []),
      ...manifests.map((path) => `${path} found`),
    ],
  };
}

async function detectIos(probe) {
  const entries = await probe.list('.');
  const xcodeEntry = entries.find((entry) => /\.(xcodeproj|xcworkspace)$/.test(entry.name));
  const hasPodfile = await probe.exists('Podfile');
  const packageSwift = await probe.read('Package.swift');
  const iosPackage = packageSwift && /\.iOS\s*\(/.test(packageSwift);
  if (!xcodeEntry && !hasPodfile && !iosPackage) return null;

  const languages = (await probe.languages('.')).filter((language) => language === 'swift' || language === 'objective-c');
  return {
    languages: languages.length ? languages : ['swift'],
    platforms: ['ios'],
    evidence: [
      ...(xcodeEntry ? [`${xcodeEntry.name} at project root`] : []),
      ...(hasPodfile ? ['Podfile at project root'] : []),
      ...(iosPackage ? ['Package.swift declares an iOS platform'] : []),
    ],
  };
}

async function firstExisting(probe, paths) {
  for (const path of paths) {
    if (await probe.exists(path)) return path;
  }
  return null;
}

function parseJson(text) {
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function unique(values) {
  return [...new Set(values)];
}
